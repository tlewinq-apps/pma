// npm run design:pack — bundles demo/celeste-design/design (manifest + frame sources) into
// src/lib/marver/fixture.generated.ts, so the built-in design canvas works on Vercel with no file-system reads.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const ROOT = "demo/celeste-design";
const files: Record<string, string> = {};
const walk = (dir: string) => {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    // design/.local is Marver's machine state (dev token, shots); pma-* are proposals written into the local canvas.
    if (name.startsWith(".") || name.startsWith("pma-")) continue;
    if (statSync(full).isDirectory()) walk(full);
    else if (/\.(tsx|json|md)$/.test(name)) files[relative(ROOT, full)] = readFileSync(full, "utf8");
  }
};
walk(join(ROOT, "design"));
writeFileSync("src/lib/marver/fixture.generated.ts", `// Generated by \`npm run design:pack\` (scripts/demo/pack-design.ts) from demo/celeste-design. Do not edit by hand.
// The Celeste design canvas PMA uses when no design repo is connected: paths are relative to the repo root.

export const FIXTURE_DESIGN: Record<string, string> = ${JSON.stringify(files, null, 2)};
`);
console.log(`Packed ${Object.keys(files).length} files`);
